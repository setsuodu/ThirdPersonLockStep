        public static Fp Sin(byte angleIndex) => Fp.FromRaw(SinRaw[angleIndex]);
        public static Fp Cos(byte angleIndex) => Fp.FromRaw(CosRaw[angleIndex]);

        // 约定：angleIndex=0 对应世界坐标系里的"正前方"(0,1)，即 (Sin=0, Cos=1)，
        // 随着 angleIndex 增大朝 +X 方向转（顺时针，从上往下看）。
        // 这个约定要跟 GameNetwork.SampleAndSendInput 里角度的计算方式，以及
        // ThirdPersonCameraRig 里镜头朝向的计算方式保持一致，三处任何一处改了朝向定义，
        // 另外两处都要跟着改，不然会出现"输入方向"和"看到的朝向"对不上的问题。
        public static FpVec2 DirFromAngle(byte angleIndex) => new FpVec2(Sin(angleIndex), Cos(angleIndex));

        /// <summary>
        /// 把一个连续弧度值（float，只允许在"发送前"这一步使用，不参与任何后续同步逻辑）
        /// 量化成 0~255 的索引。
        /// </summary>
        public static byte QuantizeAngle(float radians)
        {
            float normalized = radians / (2f * Mathf.PI);
            normalized -= Mathf.Floor(normalized);
            int idx = Mathf.RoundToInt(normalized * STEPS) % STEPS;
            if (idx < 0) idx += STEPS;
            return (byte)idx;
        }
